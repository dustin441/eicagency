-- Aurit Mediation paid-media warehouse (project lozgnyxixzfxokllevtb).
-- Populated by n8n "Aurit Meta Ads → Supabase" and "Aurit Google Ads → Supabase".
-- Safe to re-run: every statement is idempotent.

begin;

-- ─── Meta: daily campaign performance ───────────────────────────────────────
create table if not exists public.aurit_meta (
  id bigint generated by default as identity primary key,
  date date not null,
  account_id text not null check (account_id = '827752439223069'),
  campaign_id text not null,
  campaign_name text not null,
  objective text,
  ad_channel text not null default 'Meta' check (ad_channel = 'Meta'),
  impressions bigint not null default 0 check (impressions >= 0),
  reach bigint not null default 0 check (reach >= 0),
  clicks bigint not null default 0 check (clicks >= 0),
  link_clicks bigint not null default 0 check (link_clicks >= 0),
  landing_page_views bigint not null default 0 check (landing_page_views >= 0),
  cost numeric(14, 2) not null default 0 check (cost >= 0),
  conversions numeric(14, 2) not null default 0 check (conversions >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (date, campaign_id)
);

create index if not exists aurit_meta_date_idx on public.aurit_meta (date);

comment on table public.aurit_meta is
  'Daily campaign-level Meta Ads performance for Aurit Mediation (act_827752439223069); USD, America/Los_Angeles.';
comment on column public.aurit_meta.conversions is
  'Sum of every conversion type stored in aurit_conversions for this campaign/day (platform = Meta).';

-- ─── Google: daily campaign performance (whole account, incl. Rocket Clicks) ─
create table if not exists public.aurit_google (
  id bigint generated by default as identity primary key,
  date date not null,
  account_id text not null check (account_id = '6016279098'),
  campaign_id text not null,
  campaign_name text not null,
  campaign_status text,
  campaign_type text,
  ad_channel text not null default 'Google' check (ad_channel = 'Google'),
  impressions bigint not null default 0 check (impressions >= 0),
  clicks bigint not null default 0 check (clicks >= 0),
  video_views bigint not null default 0 check (video_views >= 0),
  cost numeric(18, 6) not null default 0 check (cost >= 0),
  conversions numeric(14, 2) not null default 0 check (conversions >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (date, campaign_id)
);

create index if not exists aurit_google_date_idx on public.aurit_google (date);

comment on table public.aurit_google is
  'Daily campaign-level Google Ads performance for Aurit Mediation (CID 601-627-9098), whole account: EIC YouTube + Rocket Clicks Search/PMax.';
comment on column public.aurit_google.conversions is
  'Sum of every conversion action stored in aurit_conversions for this campaign/day (platform = Google, metrics.all_conversions).';

-- ─── Conversions by type (both platforms) ───────────────────────────────────
-- One row per platform/campaign/day/conversion type so the dashboard can show
-- each type separately or aggregated.
create table if not exists public.aurit_conversions (
  id bigint generated by default as identity primary key,
  date date not null,
  platform text not null check (platform in ('Meta', 'Google')),
  campaign_id text not null,
  conversion_type text not null,
  conversion_label text not null,
  conversions numeric(14, 4) not null default 0 check (conversions >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (date, platform, campaign_id, conversion_type)
);

create index if not exists aurit_conversions_date_idx on public.aurit_conversions (date);

comment on table public.aurit_conversions is
  'Aurit conversions by type. Meta: curated non-overlapping action types (aliases never summed). Google: metrics.all_conversions per conversion action.';

-- Service-role only (dashboard reads server-side with the service key).
alter table public.aurit_meta enable row level security;
alter table public.aurit_google enable row level security;
alter table public.aurit_conversions enable row level security;
revoke all on table public.aurit_meta, public.aurit_google, public.aurit_conversions from public, anon, authenticated;
grant select, insert, update, delete on table public.aurit_meta, public.aurit_google, public.aurit_conversions to service_role;
grant usage, select on sequence public.aurit_meta_id_seq, public.aurit_google_id_seq, public.aurit_conversions_id_seq to service_role;

commit;
